// Langue de l'interface : celle de Home Assistant (français ou anglais, anglais par défaut)
let lang: "en" | "fr" = (navigator.language || "").startsWith("fr") ? "fr" : "en";

export function setLang(hass?: HomeAssistant) {
  const l = hass?.locale?.language ?? hass?.language;
  if (l) lang = l.startsWith("fr") ? "fr" : "en";
}

/** Texte traduit ; `{nom}` est remplacé par `vars.nom`. */
export function tr(key: string, vars: Record<string, string | number> = {}): string {
  const text = (lang === "fr" ? fr : en)[key as Key] ?? en[key as Key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}

/** Indique si une clé de traduction existe. */
export const hasKey = (key: string) => key in en;
